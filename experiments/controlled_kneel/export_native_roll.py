"""Generate fixed native targets offline; never access a robot or run online IK."""
import argparse,json,sys
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from experiments.controlled_kneel.simulate import setup,pose,hug_pose

def export(config,output):
    m,d,qa,va,act,effort,cp,names=setup()
    poses=[]
    for i in (1,2,3):
        q=pose(d.qpos[qa],config['hip'+str(i)],config['knee'+str(i)],config['ankle'+str(i)],config['waist'+str(i)],[-1.,-2.,-2.3][i-1],[.8,.7,.8][i-1])
        q,_=hug_pose(m,qa,q);poses.append(q)
    ranges=m.jnt_range[[m.joint(n+'_joint').id for n in names]]
    values=dict(pose1=poses[0],pose2=poses[1],pose3=poses[2],qmin=ranges[:,0]+.01,qmax=ranges[:,1]-.01,effort=effort,kp=np.array([120,100,60,160,50,40]*2+[50,50,60]+[45,35,25,35,10,10,10]*2),kd=np.array([8,7,4,10,4,3]*2+[4,4,5]+[4,3,2,3,1,1,1]*2))
    times=config.get('times',[0,1.,1.7,2.2])
    scalars=dict(first_stage_s=times[1],second_stage_s=times[2],tuck_stage_s=times[3],ankle_start_s=config.get('ankle_start_s',0.),upper_fold_fraction=config.get('upper_fold_fraction',1.))
    feedback=config.get('ankle_feedback')
    if feedback is not None and (set(feedback)!={'base','rate_gain','pitch_gain','maximum'} or not all(np.isfinite(v) for v in feedback.values()) or not 0<=feedback['base']<=feedback['maximum']<=.5):raise ValueError('Invalid ankle feedback configuration')
    scalars['adaptive_ankle_enabled']=1 if feedback else 0
    scalars.update(dynamic_transfer_s=config.get('dynamic_transfer_s',.12),dynamic_crouch_s=config.get('dynamic_crouch_s',.8),dynamic_swing_extension=config.get('dynamic_swing_extension',.12))
    if not 0<=scalars['dynamic_transfer_s']<=.3 or not .4<=scalars['dynamic_crouch_s']<=1.4 or not 0<=scalars['dynamic_swing_extension']<=.3:raise ValueError('Invalid dynamic transfer parameters')
    for key,value in (feedback or dict(base=.25,rate_gain=1.4,pitch_gain=0,maximum=.5)).items():scalars['adaptive_ankle_'+key]=value
    if not 0<times[1]<times[2]<times[3]<7 or not 0<scalars['upper_fold_fraction']<=1 or not 0<=scalars['ankle_start_s']<times[1]:raise ValueError('Invalid trajectory timing')
    output=Path(output);output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('// Generated by experiments/controlled_kneel/export_native_roll.py; offline IK only.\n#pragma once\n#include <array>\nnamespace sonic_bridge { namespace roll_parameters {\n'+''.join('constexpr std::array<double,29> '+k+'{{'+','.join(format(float(x),'.12g') for x in v)+'}};\n' for k,v in values.items())+''.join('constexpr double '+k+'='+format(float(v),'.12g')+';\n' for k,v in scalars.items())+'}}\n')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config',type=Path,default=ROOT/'experiments/controlled_kneel/roll_config.json')
    p.add_argument('--output',type=Path,default=ROOT/'onboardmimic/robots/unitree_g1/native_bridge/roll_parameters.hpp')
    a=p.parse_args();export(json.loads(a.config.read_text()),a.output)
